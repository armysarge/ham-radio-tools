// Packs the DVOACAP ionospheric coefficient files (CCIR/URSI maps, 12 months) into src/lib/voacap/coeffs.ts as base64.
// Usage: node scripts/build-voacap-data.mjs <path to a checkout of github.com/VE3NEA/DVOACAP>
// Each month = Coeff<MM>.dat (38 480 bytes) followed by FOF2CCIR<MM>.dat (7 904 bytes), little-endian IEEE singles/int32 exactly as the original reads them.
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { createHash } from 'node:crypto'

const src = process.argv[2]
if (!src) { console.error('Usage: node scripts/build-voacap-data.mjs <DVOACAP checkout>'); process.exit(1) }
const COEFF = 38480, FOF2 = 7904
const parts = [], hashes = []
for (let m = 1; m <= 12; m++) {
  const mm = String(m).padStart(2, '0')
  const a = await readFile(join(src, 'DVoaData', `Coeff${mm}.dat`)), b = await readFile(join(src, 'DVoaData', `FOF2CCIR${mm}.dat`))
  if (a.length !== COEFF || b.length !== FOF2) throw new Error(`Unexpected size for month ${mm}: ${a.length} / ${b.length}`)
  const both = Buffer.concat([a, b])
  parts.push(both.toString('base64')); hashes.push(createHash('sha256').update(both).digest('hex').slice(0, 12))
}
const out = `// GENERATED by scripts/build-voacap-data.mjs from DVOACAP's DVoaData folder (MIT, Copyright (c) 2013-2025 Alex Shovkoplyas, VE3NEA). Do not edit.
// One base64 string per month (January first): Coeff<MM>.dat (${COEFF} bytes) then FOF2CCIR<MM>.dat (${FOF2} bytes). sha256 prefixes: ${hashes.join(' ')}
export const COEFF_BYTES = ${COEFF}
export const FOF2_BYTES = ${FOF2}
export const VOACAP_MONTHS: string[] = [
${parts.map((p) => `  '${p}',`).join('\n')}
]
`
await writeFile(new URL('../src/lib/voacap/coeffs.ts', import.meta.url), out)
console.log(`wrote src/lib/voacap/coeffs.ts (${(out.length / 1024).toFixed(0)} KB)`)
